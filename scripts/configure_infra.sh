#!/usr/bin/env bash
# Generate a tuned .env for docker compose based on target infrastructure.
#
# Usage: ./scripts/configure_infra.sh [low|medium|high|auto]
#
#   low    2-4 cores, 8 GB RAM    edge / laptop / small VPS  (int8, no pinning)
#   medium 8 cores, 16 GB RAM      standard production server (int8, pinning)
#   high   16-32+ cores, 32 GB+    dedicated accuracy node   (float32, pinning)
#   auto   detect cores/RAM and pick the best fit (default)
set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROFILE="${1:-auto}"

detect_cores() {
  if command -v nproc >/dev/null 2>&1; then nproc
  elif command -v sysctl >/dev/null 2>&1 && sysctl -n hw.ncpu >/dev/null 2>&1; then sysctl -n hw.ncpu
  else echo 4; fi
}

detect_ram_gb() {
  if [[ -r /proc/meminfo ]]; then awk '/^MemTotal:/{printf "%d", $2/1024/1024; exit}' /proc/meminfo
  elif command -v sysctl >/dev/null 2>&1 && sysctl -n hw.memsize >/dev/null 2>&1; then echo $(( $(sysctl -n hw.memsize) / 1024 / 1024 / 1024 ))
  else echo 8; fi
}

CORES="$(detect_cores)"
RAM_GB="$(detect_ram_gb)"

case "$PROFILE" in
  low|medium|high) ;;
  auto)
    if (( CORES < 8 || RAM_GB < 10 )); then PROFILE=low
    elif (( CORES < 16 )); then PROFILE=medium
    else PROFILE=high; fi ;;
  *) echo "usage: $0 [low|medium|high|auto]" >&2; exit 2 ;;
esac

case "$PROFILE" in
  low)
    WHISPER_COMPUTE_TYPE=int8
    STT_WORKERS=1; TTS_WORKERS=1
    STT_OMP_THREADS=2; TTS_OMP_THREADS=2
    STT_CPUS=1.5; TTS_CPUS=1.5
    STT_MEM=4g; TTS_MEM=4g
    ;;
  medium)
    WHISPER_COMPUTE_TYPE=int8
    STT_WORKERS=2; TTS_WORKERS=2
    STT_OMP_THREADS=4; TTS_OMP_THREADS=4
    STT_CPUS=4.0; TTS_CPUS=4.0
    STT_MEM=8g; TTS_MEM=8g
    ;;
  high)
    WHISPER_COMPUTE_TYPE=float32
    STT_WORKERS=4; TTS_WORKERS=4
    STT_OMP_THREADS=8; TTS_OMP_THREADS=8
    STT_CPUS=8.0; TTS_CPUS=8.0
    STT_MEM=16g; TTS_MEM=16g
    ;;
esac

# Hard pinning for profiles that assume a dedicated machine; empty cpuset
# (= disabled) on the low profile so it stays safe on shared/small hosts.
STT_CPUSET=""; TTS_CPUSET=""
HALF=$(( CORES / 2 ))
if [[ "$PROFILE" != "low" ]] && (( HALF >= 4 )); then
  STT_CPUSET="0-$(( HALF - 1 ))"
  TTS_CPUSET="${HALF}-$(( CORES - 1 ))"
fi

# Never give a service more OMP threads or workers than the cores it can use.
(( STT_OMP_THREADS > CORES )) && STT_OMP_THREADS=$CORES
(( TTS_OMP_THREADS > CORES )) && TTS_OMP_THREADS=$CORES
if [[ -n "$STT_CPUSET" ]]; then
  (( STT_OMP_THREADS > HALF )) && STT_OMP_THREADS=$HALF
  (( STT_WORKERS > HALF )) && STT_WORKERS=$HALF
fi
if [[ -n "$TTS_CPUSET" ]]; then
  (( TTS_OMP_THREADS > HALF )) && TTS_OMP_THREADS=$HALF
  (( TTS_WORKERS > HALF )) && TTS_WORKERS=$HALF
fi

ENV_FILE="$ROOT/.env"
if [[ -e "$ENV_FILE" ]]; then cp "$ENV_FILE" "$ENV_FILE.bak"; fi

cat > "$ENV_FILE" <<EOF
# Generated by scripts/configure_infra.sh — profile: $PROFILE
# Detected host: ${CORES} cores, ${RAM_GB} GB RAM ($(date "+%Y-%m-%d %H:%M:%S"))
# Safe to hand-edit; docker compose reads this file automatically.

# Whisper quantisation: int8 | int8_float32 | float32
WHISPER_COMPUTE_TYPE=$WHISPER_COMPUTE_TYPE

# inference worker pool size per service
STT_WORKERS=$STT_WORKERS
TTS_WORKERS=$TTS_WORKERS

# BLAS / CTranslate2 / torch threads per service
STT_OMP_THREADS=$STT_OMP_THREADS
TTS_OMP_THREADS=$TTS_OMP_THREADS

# soft CPU quota per service (docker "cpus")
STT_CPUS=$STT_CPUS
TTS_CPUS=$TTS_CPUS

# optional hard core pinning; empty = disabled
STT_CPUSET=$STT_CPUSET
TTS_CPUSET=$TTS_CPUSET

# memory limits per service
STT_MEM=$STT_MEM
TTS_MEM=$TTS_MEM
EOF

echo "wrote $ENV_FILE  (profile: $PROFILE, host: ${CORES} cores / ${RAM_GB} GB)"
if [[ -e "$ENV_FILE.bak" ]]; then echo "previous config backed up to $ENV_FILE.bak"; fi
